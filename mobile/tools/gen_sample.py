"""Writes web/js/sample.js from the SAMPLE_LAB_REPORT_TEXT constant in app.py (parsed with ast, app.py is not imported)."""
import ast, json, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
tree = ast.parse((root / "app.py").read_text(encoding="utf-8"))
text = None
for node in tree.body:
    if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "SAMPLE_LAB_REPORT_TEXT" for t in node.targets):
        text = ast.literal_eval(node.value)
if text is None:
    sys.exit("SAMPLE_LAB_REPORT_TEXT not found in app.py")
out = pathlib.Path(__file__).resolve().parents[1] / "web" / "js" / "sample.js"
out.write_text("/* generated by tools/gen_sample.py from app.py - do not edit */\nwindow.NUTRI_SAMPLE_REPORT = %s;\n" % json.dumps(text.strip("\n")), encoding="utf-8")
print("wrote", out, len(text), "chars")
